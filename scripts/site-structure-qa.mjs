import fs from "node:fs";

const read = path => fs.readFileSync(path, "utf8");
const fail = message => { throw new Error(message); };
const assert = (condition, message) => condition || fail(message);

const routes = JSON.parse(read("_routes.json"));
assert(Array.isArray(routes.include), "_routes.json include must be an array");
assert(routes.include.includes("/guides/*"), "Missing /guides/* in _routes.json");
assert(routes.include.includes("/games/*"), "Missing /games/* in _routes.json");
assert(routes.include.includes("/api/*"), "Missing /api/* in _routes.json");

const index = read("index.html");
assert(index.includes('href="/guides/"'), "Homepage is missing a server-rendered Guides link");
assert(index.includes('id="editorial-guides-home"'), "Homepage is missing the server-rendered editorial guides section");
assert(index.includes("What Are Browser Games?"), "Homepage is missing the browser gaming overview");
assert(index.includes("BrainrotGames Overview"), "Homepage is missing the site overview table");
assert(index.toLowerCase().includes("why use brainrotgames"), "Homepage is missing the value proposition section");
assert(index.includes("adsbygoogle.js?client=ca-pub-1559302511010806"), "Homepage is missing the AdSense verification script");

const play = read("play.html");
assert(play.includes('id="what-to-expect"'), "Game pages are missing the What to Expect section");
assert(play.includes('id="gameplay-overview"'), "Game pages are missing the Gameplay Overview section");
assert(play.includes('id="game-fit"'), "Game pages are missing the game-fit section");
assert(play.includes("Technology</span>"), "Game pages are missing technology details");

const app = read("app.js");
assert(!app.includes("insertAdjacentElement('afterend'"), "Editorial guide section must not be injected by app.js");
assert(!app.includes("mainNav.appendChild(link)"), "Guides navigation must not be injected by app.js");

const category = read("functions/games/[category].js");
assert(!category.includes("adsbygoogle.js"), "Autogenerated category pages must not include AdSense");
assert(category.includes('href=\"/guides/\"'), "Category pages should link to the editorial guides hub");

const guideRenderer = read("functions/guides/[slug].js");
assert(guideRenderer.includes("ARTICLES"), "Guide renderer is missing the editorial article collection");
for (const slug of [
  "choose-browser-game",
  "browser-game-performance",
  "mobile-browser-gaming",
  "puzzle-game-strategy",
  "browser-racing-tips",
  "keyboard-mouse-controls",
  "two-player-browser-games",
  "how-we-select-games"
]) {
  assert(guideRenderer.includes(`\"${slug}\"`), `Guide renderer is missing ${slug}`);
}

for (const file of ["about.html", "contact.html", "privacy.html", "cookies.html", "terms.html", "guides/index.html"]) {
  const html = read(file);
  assert(html.includes("adsbygoogle.js?client=ca-pub-1559302511010806"), `${file} is missing the AdSense verification script`);
}

const sitemap = read("functions/sitemap.xml.js");
for (const id of ["7RU2YF", "011ODI", "ANMAR4"]) {
  assert(sitemap.includes(`\"${id}\"`), `Sitemap blocklist is missing ${id}`);
}

const workflow = read(".github/workflows/game-qa.yml");
for (const path of ["scripts/site-structure-qa.mjs", "_routes.json", "index.html", "app.js", "functions/guides/**", "functions/games/**", "functions/sitemap.xml.js"]) {
  assert(workflow.includes(`\"${path}\"`), `Workflow does not trigger on ${path}`);
}

